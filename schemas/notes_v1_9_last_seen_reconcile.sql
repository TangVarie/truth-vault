--
-- 给 notes 加"上一次在飞书源里见到它是什么时候"。
-- 来源: 2026-08-24 跨库审计 COR-011。
--
-- ── 治的是什么 ────────────────────────────────────────────────────────
--
-- 主同步只 upsert 源里**存在**的行, 没有任何对账。飞书那边删掉一条记录、
-- 或者把它移到别的表, TV 这边**永远不会知道** —— 那条 note 连同它的
-- 评论、指标快照、精华标注、lesson card 一起长期留着, 而且会继续被下游
-- 消费(馆员借阅、三生六部的参考样本、autowriter 的正例)。
--
-- ── 为什么这次**只加证据, 不做删除** ──────────────────────────────────
--
-- 「这次同步没看见它」和「它被删了」**不是一回事**, 而且区别是致命的:
--
--   · sync 有 ``--limit`` —— 带上之后循环会中途 break, 后面的记录一条都
--     不会被"看见";
--   · 多表合并时任何一张表抓失败, 那张表里的记录也全都"没看见";
--   · 运营把记录移到另一张已配置的表 = 换了 note_id, 老的那条"消失"了,
--     但内容还在。
--
-- 按"没看见就标删"实现的话, **一次带 --limit 的手动同步就能把整个项目
-- 标成已删除**。而 notes 有六张表 ON DELETE CASCADE, 另有
-- ``synced_to_ssll_at`` 标着已经推到**另一个数据库**(三生六部)的行 ——
-- 那边没有外键, 删了就是孤儿。这个方向的错误不可逆。
--
-- 所以这一版只做**可证伪的记录**: 每次**完整**同步(没有 --limit 截断、
-- 所有已配置的表都抓成功)给见到的 note 盖一个 run 戳。没被盖到的那些是
-- **候选**, 由对账报告列出来给人看 —— 删不删、什么时候删, 是产品判断,
-- 不该由一次 schema 迁移替人决定。
--
-- ⚠️ 只有完整同步才盖戳。部分同步**一个戳都不盖** —— 否则"上次见到"这个
--    数会被一次 --limit 跑成一半新一半旧, 那比没有这个字段更坏。
--
-- 幂等: ADD COLUMN IF NOT EXISTS / CREATE INDEX IF NOT EXISTS。
-- ════════════════════════════════════════════════════════════════════

-- 最后一次在源里见到它的时刻。NULL = 本列上线前就存在的行, 还没经历过一次
-- 完整同步 —— **不代表它消失了**, 对账报告要把这两者分开。
ALTER TABLE truth_vault.notes
    ADD COLUMN IF NOT EXISTS last_seen_at TIMESTAMPTZ;

-- 盖戳的那次运行的 id。有了它, "这条是本次见到的"就是一个**精确相等**的
-- 判断, 不依赖时钟(并发跑、时区、容器时钟漂移都不影响)。
ALTER TABLE truth_vault.notes
    ADD COLUMN IF NOT EXISTS last_seen_run_id TEXT;

-- 对账报告按 (project_id, last_seen_run_id) 捞"本次没见到的", 这个索引让它
-- 在几万行上也是一次索引扫描。
CREATE INDEX IF NOT EXISTS notes_last_seen_idx
    ON truth_vault.notes (project_id, last_seen_run_id);

COMMENT ON COLUMN truth_vault.notes.last_seen_at IS
    '最后一次在飞书源里见到它的时刻; 只有**完整**同步(无 --limit 截断且所有'
    '已配置表都抓成功)才会更新。NULL = 还没经历过完整同步, **不等于已删除**。'
    '见审计 COR-011。';
COMMENT ON COLUMN truth_vault.notes.last_seen_run_id IS
    '盖上 last_seen_at 的那次运行 id。对账靠它做精确相等判断, 不依赖时钟。';
